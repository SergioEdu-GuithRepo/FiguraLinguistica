/**
 * Kanji do percurso de japonês, por ordem de introdução/frequência (Fase 2 do documento:
 * "kanji introduzidos gradualmente por frequência e sempre com furigana opcional").
 *
 * KANJI_ORDER define o conjunto permitido no conteúdo curado (o validador verifica-o).
 * KANJI tem os detalhes de cada carácter, na mesma ordem.
 */

export interface KanjiExample {
  /** Palavra com o kanji, tal como aparece no conteúdo (ex.: "日本"). */
  word: string;
  /** Leitura em hiragana (ex.: "にほん"). */
  reading: string;
  /** Romaji Hepburn (ex.: "nihon"). */
  romaji: string;
  /** Tradução portuguesa curta. */
  pt: string;
}

export interface Kanji {
  /** O carácter (um só). */
  char: string;
  /** Significado(s) em português, curto. Ex.: "dia; sol". */
  meaning: string;
  /** Leituras on'yomi em katakana. Ex.: ["ニチ", "ジツ"]. */
  on: string[];
  /** Leituras kun'yomi em hiragana (okurigana após "."). Ex.: ["ひ", "-か"]. */
  kun: string[];
  /** Número de traços. */
  strokes: number;
  /** 2 ou 3 palavras de exemplo frequentes (de preferência as que aparecem nas unidades). */
  examples: KanjiExample[];
  /** Dica mnemónica em português (uma linha), opcional. */
  tip?: string;
}

